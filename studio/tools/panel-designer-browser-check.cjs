// Run against the Studio server with PLAYWRIGHT_MODULE pointing to Playwright if needed.
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.STUDIO_URL || 'http://127.0.0.1:8788/studio/index.html';
(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const modal = page.locator('.appearance-modal-backdrop');
  async function openAppearance() {
    await page.locator('a[data-tab="interface"]').click();
    await modal.waitFor({state:'visible'});
  }
  try {
    await page.goto(`${base}#engines`);
    assert.equal(await page.locator('.appearance-modal-backdrop').count(), 0);
    await openAppearance();
    assert.equal(await page.evaluate(() => location.hash), '#engines', 'Interface opens as a popup without navigating away');
    assert.equal(await modal.locator('.appearance-preset-btn').count(), 14);
    await modal.locator('.appearance-preset-btn[data-preset-key="blueprint"]').click();
    await modal.locator('.appearance-seg').nth(0).getByRole('button', {name:'Rounded'}).click();
    await modal.locator('.appearance-seg').nth(2).getByRole('button', {name:'Comfortable'}).click();
    await modal.locator('.appearance-seg').nth(4).getByRole('button', {name:'Visible'}).click();
    await modal.locator('.appearance-seg').nth(5).getByRole('button', {name:'Medium'}).click();
    assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--bg').trim()), '#0a1018');
    await modal.locator('.appearance-modal-header button').click();
    await page.locator('a[data-tab="routing"]').click();
    const routingTheme = await page.evaluate(() => {
      const tab=document.querySelector('#routing-tab'), desk=document.createElement('div'); desk.className='rd-desk'; tab.append(desk);
      const result={surface:getComputedStyle(tab).getPropertyValue('--rd-surface').trim(),studioSurface:getComputedStyle(document.documentElement).getPropertyValue('--surface').trim(),desk:getComputedStyle(desk).backgroundColor}; desk.remove(); return result;
    });
    assert.equal(routingTheme.surface, routingTheme.studioSurface, 'Routing patch desk uses the global Studio surface token');
    assert.equal(routingTheme.desk, await page.evaluate(() => {const e=document.createElement('div');e.style.background='var(--surface)';document.body.append(e);const v=getComputedStyle(e).backgroundColor;e.remove();return v;}));
    await page.locator('a[data-tab="locks"]').click();
    const plotTheme = await page.evaluate(() => {
      const plot=document.querySelector('#locks-root .lock-shape');
      return plot ? {plot:getComputedStyle(plot).backgroundColor,surface:getComputedStyle(document.documentElement).getPropertyValue('--surface-2').trim()} : null;
    });
    assert.ok(plotTheme, 'Knob record should render its graph slots');
    assert.equal(plotTheme.plot, await page.evaluate(() => {const e=document.createElement('div');e.style.background='var(--surface-2)';document.body.append(e);const v=getComputedStyle(e).backgroundColor;e.remove();return v;}), 'Knob record plots should follow the Studio surface theme');
    await page.locator('a[data-tab="palette"]').click();
    await page.reload();
    await openAppearance();
    assert.equal(await modal.locator('.appearance-preset-btn.active').getAttribute('data-preset-key'), 'blueprint');
    assert.equal(await page.evaluate(() => localStorage.getItem('panel-designer:viewContrast')), '0.45');
    await modal.locator('.appearance-modal-header button').click();
    const opened = page.waitForEvent('popup');
    await page.locator('a[data-tab="panel-designer"]').click();
    const designer = await opened;
    await designer.locator('.workspace').waitFor({ state: 'visible' });
    assert.match(designer.url(), /panel-designer\/index\.html/);
    assert.equal(await page.evaluate(() => location.hash), '#engines');
    assert.equal(await designer.evaluate(() => document.documentElement.dataset.preset), 'blueprint');
    assert.equal(await designer.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--hp-grid-opacity').trim()), '0.55');
    assert.equal(await designer.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--theme-radius').trim()), '8px');
    assert.equal(await designer.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--theme-btn-height').trim()), '38px');
    await designer.waitForFunction(() => getComputedStyle(document.documentElement).getPropertyValue('--pd-contrast').trim() === '0.45');
    await designer.getByRole('button', { name: 'Templates ▾', exact: true }).click();
    await designer.getByRole('button', { name: 'Load / Manage templates', exact: true }).click();
    await designer.locator('.template-manager-panel').waitFor({state:'visible'});
    await openAppearance();
    await modal.locator('.appearance-preset-btn[data-preset-key="graphite"]').click();
    await designer.waitForFunction(() => document.documentElement.dataset.preset === 'graphite');
    assert.equal(await designer.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--hp-grid-opacity').trim()), '0.28');
    await modal.locator('.appearance-modal-header button').click();
    await page.locator('a[data-tab="slice-lab"]').click();
    await page.frameLocator('.slice-lab-frame').locator('.app').waitFor({state:'visible'});
    assert.equal(await page.locator('.slice-lab-frame').evaluate(el => getComputedStyle(el.contentDocument.querySelector('.sidebar')).backgroundColor), 'rgb(34, 34, 32)');
    const samplesTheme = await page.locator('.slice-lab-frame').evaluate(el => {
      const doc = el.contentDocument, app = doc.querySelector('.app'), card = doc.createElement('section'), grid = doc.createElement('div'), label = doc.createElement('label');
      card.className = 'source-preparation'; grid.className = 'preparation-fields'; grid.append(label); card.append(grid); app.append(card);
      const expected = doc.createElement('span'); expected.style.color = 'var(--muted)'; card.append(expected);
      const accentSurface = doc.createElement('span'); accentSurface.style.backgroundColor='var(--accent-soft)'; app.append(accentSurface);
      const textExpected = doc.createElement('span'); textExpected.style.color='var(--text)'; app.append(textExpected);
      const row = doc.createElement('div'); row.className='entry selected'; row.innerHTML='<div class="entry-main">Selected<small>Details</small></div>'; app.append(row);
      const fx = doc.createElement('div'); fx.className = 'fx-label'; app.append(fx);
      const pattern = doc.createElement('div'); pattern.className = 'pattern-editor'; app.append(pattern);
      const lane = doc.createElement('div'); lane.className='clip-lane'; app.append(lane);
      const themed = {surface:getComputedStyle(card).backgroundColor, label:getComputedStyle(label).color, expected:getComputedStyle(expected).color, fxText:getComputedStyle(fx).color, muted:getComputedStyle(expected).color, patternBg:getComputedStyle(pattern).backgroundColor, surfaceBg:getComputedStyle(card).backgroundColor, selected:getComputedStyle(row).backgroundColor, selectedExpected:getComputedStyle(accentSurface).backgroundColor,selectedText:getComputedStyle(row).color,textColor:getComputedStyle(textExpected).color,lane:getComputedStyle(lane).backgroundColor};
      card.remove(); accentSurface.remove(); textExpected.remove(); row.remove(); fx.remove(); pattern.remove(); lane.remove();
      return themed;
    });
    assert.equal(samplesTheme.surface, 'rgb(34, 34, 32)');
    assert.equal(samplesTheme.label, samplesTheme.expected);
    assert.equal(samplesTheme.fxText, samplesTheme.muted);
    assert.equal(samplesTheme.patternBg, samplesTheme.surfaceBg);
    assert.equal(samplesTheme.selected, samplesTheme.selectedExpected, 'selected pattern rows use the active appearance instead of a hardcoded dark fill');
    assert.equal(samplesTheme.selectedText, samplesTheme.textColor);
    assert.notEqual(samplesTheme.lane, 'rgb(23, 31, 41)', 'pattern lanes must not retain the hardcoded dark background');
    await designer.locator('.template-manager-panel').waitFor({state:'visible'});
    await designer.reload();
    await designer.locator('.workspace').waitFor({state:'visible'});
    await designer.getByRole('button', {name:'File ▾', exact:true}).click();
    await designer.getByRole('button', {name:'Save to Browser', exact:true}).click();
    designer.once('dialog', dialog => dialog.accept());
    await designer.getByRole('button', {name:'Save', exact:true}).click();
    await page.waitForFunction(() => localStorage.getItem('pentavox-studio-panel-local-project-index-v2'));
    assert.ok(await page.evaluate(() => localStorage.getItem('pentavox-studio-panel-local-project-index-v2')));
    await designer.getByRole('button', {name:'File ▾', exact:true}).click();
    const download = designer.waitForEvent('download');
    await designer.getByRole('button', {name:'Save Project File', exact:true}).click();
    assert.match((await download).suggestedFilename(), /\.epanel\.json$/);
    await page.locator('a[data-tab="settings"]').click();
    assert.equal(await modal.isVisible(), false);
    await openAppearance();
    await modal.locator('.studio-default-appearance').click();
    await designer.waitForFunction(() => !document.documentElement.dataset.preset || document.documentElement.dataset.preset === 'industrial');
    assert.equal(await page.evaluate(() => localStorage.getItem('pentavox.studio.appearance')), null);
    await page.locator('a[data-tab="slice-lab"]').click();
    await page.frameLocator('.slice-lab-frame').locator('.app').waitFor({state:'visible'});
    const defaultSamplesTheme = await page.locator('.slice-lab-frame').evaluate(el => {
      const doc=el.contentDocument, probe=document.createElement('span'); probe.style.background='var(--surface)'; document.body.append(probe);
      const expected=getComputedStyle(probe).backgroundColor; probe.remove();
      return {sidebar:getComputedStyle(doc.querySelector('.sidebar')).backgroundColor,expected};
    });
    assert.equal(defaultSamplesTheme.sidebar, defaultSamplesTheme.expected, 'Studio default also themes embedded Samples');
    assert.deepEqual(errors, []);
    console.log('PASS: actual Designer AppearanceModal, compact Interface launcher, shared settings, Samples, project save/export');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
