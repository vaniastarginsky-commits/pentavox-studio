function presetDef(type) {
  return COMPONENT_LIBRARY.find((d) => d.type === type) ?? COMPONENT_LIBRARY[0];
}
function presetComp(type, label, ref, x, y, rotation = 0, patch = {}) {
  const base = presetDef(type);
  return {
    ...base,
    ...patch,
    ref,
    label,
    x,
    y,
    rotation,
    notes: patch.notes ?? "",
    category: patch.category ?? base.category ?? inferCategoryForType(type),
    verificationStatus:
      patch.verificationStatus ?? base.verificationStatus ?? "approximate",
  };
}
