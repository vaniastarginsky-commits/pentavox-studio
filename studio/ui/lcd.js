const GENERIC = new Set(['struck', 'analog', 'custom', 'virtual', 'two', 'six', 'op', 'wave', 'filtered', 'particle', 'modal', 'natural', 'formant', 'string', 'granular', 'harmonic']);

// Four letters that read as the engine's name: its first meaningful word.
export function lcdLabel(name = '') {
  const words = String(name).toUpperCase().replace(/[^A-Z0-9]+/g, ' ').trim().split(' ').filter(Boolean);
  if (!words.length) return '----';
  const pick = words.find((w) => !GENERIC.has(w.toLowerCase()) && w.length >= 3) ?? words[words.length - 1];
  return pick.slice(0, 4).padEnd(4, ' ');
}

// SVG with 2x2 glyphs; lit dots use currentColor so the bank colour can drive the glow.
export function lcdSvg(text) {
  const chars = String(text).toUpperCase().padEnd(4, ' ').slice(0, 4).split('');
  const dot = 1.0, pitch = 1.25, glyphW = 5 * pitch, glyphH = 7 * pitch, gapX = 1.4, gapY = 1.8, pad = 2;
  const width = pad * 2 + glyphW * 2 + gapX, height = pad * 2 + glyphH * 2 + gapY;
  let lit = '', off = '';
  chars.forEach((ch, i) => {
    const rows = FONT[ch] ?? FONT[' ']; const ox = pad + (i % 2) * (glyphW + gapX); const oy = pad + Math.floor(i / 2) * (glyphH + gapY);
    rows.forEach((row, y) => [...row].forEach((bit, x) => {
      const rect = `<rect x="${(ox + x * pitch).toFixed(2)}" y="${(oy + y * pitch).toFixed(2)}" width="${dot}" height="${dot}" rx=".25"/>`;
      if (bit === '1') lit += rect; else off += rect;
    }));
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width.toFixed(2)} ${height.toFixed(2)}" preserveAspectRatio="xMidYMid meet"><rect width="100%" height="100%" rx="3" fill="#10140d"/><g fill="currentColor" opacity=".11">${off}</g><g fill="currentColor">${lit}</g></svg>`;
}

